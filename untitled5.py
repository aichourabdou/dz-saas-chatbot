# 3. صياغة ملقن النظام الذكي وتوجيهه للحديث بالدارجة الجزائرية
system_instruction = f"""
أنت موظف خدمة عملاء ذكي، محترف ومؤدب جداً لمتجر عربي اسمه "أناقة ديزاد".
يجب أن تتحدث حصراً باللغة العربية اللطيفة والمفهومة لزبائن الصفحة مع استخدام إيموجيات تجارية ودية.

إليك وثيقة السياسات والأسعار والمنتجات الرسمية الخاصة بالمتجر، وعليك الإجابة منها بدقة تامة وبذكاء:
{store_policy_text}

شروط صارمة جداً:
1. أجب عن سؤال الزبون بوضوح وبساطة بالدارجة وبناءً على دليل السياسات والمنتجات المذكور أعلاه فقط.
2. إذا سألك الزبون عن منتج أو سعر أو سياسة غير مذكورة في الدليل، قل له بأدب وبطريقة تجارية محببة: "سمحلي هادي المعلومة ماهيش متوفرة عندي حالياً، بصح تقدر تخلي رسالة وسيقوم موظف بشري بالرد عليك فوراً".
3. لا تخترع أي معلومات أو أسعار أو مقاسات من عندك خارج نطاق الدليل.
4. اجعل الإجابة مختصرة، مفيدة، ومشجعة للزبون على الشراء وتأكيد الطلبية.
"""

def chat_function(message, history):
    # الطريقة الحديثة والآمنة لبناء السجل المتوافق مع إصدارات جيراديو الجديدة والقديمة
    messages = [{"role": "system", "content": system_instruction}]

    # قراءة السجل القديم بأمان وتفادي خطأ 'list'
    for chat in history:
        if isinstance(chat, dict):
            # إذا كان السجل على شكل قاموس (الإصدارات الجديدة)
            messages.append({"role": chat.get("role", "user"), "content": str(chat.get("content", ""))})
        elif isinstance(chat, (list, tuple)) and len(chat) >= 2:
            # إذا كان السجل على شكل مصفوفة قديمة [user, assistant]
            messages.append({"role": "user", "content": str(chat[0])})
            messages.append({"role": "assistant", "content": str(chat[1])})

    # إضافة الرسالة الحالية للزبون
    messages.append({"role": "user", "content": str(message)})

    try:
        response = client.chat.completions.create(
            model="openai/gpt-oss-20b",
            messages=messages,
            temperature=0.3
        )
        return response.choices[0].message.content  # تم إصلاح طريقة جلب محتوى الرسالة هنا بدقة
    except Exception as e:
        return f"حدث خطأ في النظام: {str(e)}"

# 4. بناء واجهة مستخدم جيراديو المخصصة للهواتف
with gr.Blocks(css=".gradio-container {max-width: 420px !important; margin: auto !important;}", theme=gr.themes.Default()) as demo:
    gr.Markdown("<h3 style='text-align: center;'>🤖 المساعد الذكي لخدمة العملاء (أناقة ديزاد)</h3>")
    gr.ChatInterface(
        fn=chat_function,
        textbox=gr.Textbox(placeholder="...أكتب سؤالك هنا بالدارجة", scale=7)
    )

# تشغيل البوت وإطلاق الرابط العام المجاني
demo.launch(inline=True, share=True, height=650)